"""Loading and saving a map layer: ``data/theaters/<map>/map.json``.

The file is a ``Theater`` encoded like a save (``campaign.persist.encode``), with a header:

    {"format": 1, "built_at": "...", "area": {"center": "Khalkhalah", "x": ..., "y": ..., "radius_nm": 100},
     "theater": Theater}

It is generated by ``python3 -m tools.extract_theater`` and tracked in git; hand clean-up goes in
``edits.toml`` next to it, which every build applies. See docs/theater.md.
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from .model import Link, ObjectiveDef, Theater
from .persist import SaveError, decode, encode

ROOT = Path(__file__).resolve().parent.parent
FORMAT = 1


def theater_dir(map_name: str) -> Path:
    return ROOT / "data" / "theaters" / map_name.lower()


def dumps(theater: Theater, header: dict[str, Any]) -> str:
    """JSON with one objective or link per line, so a rebuild's git diff shows what changed."""
    def one(v: Any) -> str:
        return json.dumps(encode(v), ensure_ascii=False, separators=(",", ":"))

    head = json.dumps({"format": FORMAT, **header}, ensure_ascii=False)[:-1]
    objs = ",\n".join(f"  {json.dumps(k)}:{one(o)}" for k, o in sorted(theater.objectives.items()))
    links = ",\n".join(f"  {one(ln)}" for ln in theater.links)
    return (f'{head}, "theater": {{"map": {json.dumps(theater.map)},\n "objectives": {{\n{objs}\n }},\n'
            f' "links": [\n{links}\n ]}}}}\n')


def load_theater(path: Path) -> Theater:
    try:
        raw = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as e:
        raise SaveError(f"{path}: {e}") from None
    if raw.get("format") != FORMAT:
        raise SaveError(f"{path}: format {raw.get('format')!r}, expected {FORMAT}")
    return decode(Theater, raw["theater"], "theater")


def neighbours(theater: Theater, oid: str) -> list[tuple[str, Link]]:
    """(other objective id, link) for every link touching ``oid``."""
    return [(ln.b if ln.a == oid else ln.a, ln) for ln in theater.links if oid in (ln.a, ln.b)]


def by_type(theater: Theater, *types) -> list[ObjectiveDef]:
    return [o for o in theater.objectives.values() if o.type in types]
